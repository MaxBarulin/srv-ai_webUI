"""Расшифровка изображений (§16).

Картинка уходит модели один раз — на том ходу, к которому её приложили.
Ни в базе, ни в контексте следующих ходов её нет: держать десяток base64-картинок
в каждом запросе означало бы забить контекст и пересчитывать их заново каждый ход.
Раньше на её месте оставалась пометка «приложено изображение: чертёж.png» — имя
файла и ничего больше, так что на втором вопросе модель про содержимое картинки
уже не знала. Теперь остаётся расшифровка — текстовый пересказ.

**Когда она снимается.** При отправке сообщения, внутри хода
(`app/routers/chat.py`), а не при закреплении файла. Разбор файла — дело
дешёвое и делается сразу, но расшифровка это полноценная генерация, и ей место
там, где пользователь видит, чем занята модель, и где её обрывает кнопка
«Остановить». Позже, при сборке истории, снимать её уже поздно: картинки в
базе нет.

Если расшифровка вышла неверной, лечится перезаливкой файла — желательно
с конкретным вопросом, иначе выйдет тот же самый общий пересказ.
"""
from __future__ import annotations

from app.config import settings
from app.llm import LLMError, stream_chat

TRANSCRIBE_SYSTEM = (
    "Ты расшифровываешь изображения для инженеров судостроительного завода. "
    "Твой пересказ — единственное, что останется от картинки в переписке: "
    "сама картинка дальше не сохраняется."
)

TRANSCRIBE_PROMPT = (
    "Перескажи текстом всё, что есть на изображении. Ничего не пропускай "
    "и ничего не додумывай.\n"
    "— надписи, подписи, штампы, номера — дословно;\n"
    "— таблицы — таблицей Markdown, со всеми ячейками;\n"
    "— числа, размеры, допуски, марки материалов — точно как написано;\n"
    "— чертёж или схема — что изображено, из каких элементов, как связаны;\n"
    "— график — оси, единицы, подписи, характерные точки;\n"
    "— фотография — что на ней и в каком состоянии.\n"
    "Неразборчивое так и помечай: «неразборчиво».\n"
    "В ответе — только пересказ, без вступления и без выводов."
)

MULTI_IMAGE_HINT = (
    "\nИзображений {count}. Разбери каждое по очереди, отделяя строкой "
    "«— лист {{номер}} —»."
)


def enabled() -> bool:
    """Включена ли расшифровка (IMAGE_TRANSCRIBE).

    Спрашивать надо ДО того, как показывать «расшифровываю»: иначе при
    выключенной настройке пользователь видит плашку о работе, которой нет.
    """
    return settings.image_transcribe


async def transcribe_images(filename: str, images: list[str]) -> tuple[str, str]:
    """Расшифровать картинки одного вложения.

    Все картинки вложения уходят одним запросом: у PDF в режиме «картинками»
    их столько, сколько страниц, и отдельная генерация на страницу означала бы
    минуты ожидания вместо десятков секунд.

    Возвращает (расшифровка, предупреждение). Обе строки могут быть пустыми:
    неудача расшифровки не должна рушить весь ход — на этом ходу модель всё
    равно смотрит на саму картинку, теряется только пересказ для следующих.

    Своего ограничителя нет намеренно. Пока расшифровка висела на загрузке
    файла, он был нужен: десяток крошечных PNG занимал модель, не отправив в
    чат ни одного сообщения. Теперь расшифровку нельзя запустить, не отправив
    сообщение, а отправка и так стоит генерации — усиления больше нет, и
    очередь пусть держит llama.cpp, как и во всём остальном.
    """
    if not images or not settings.image_transcribe:
        return "", ""
    prompt = TRANSCRIBE_PROMPT
    if len(images) > 1:
        prompt += MULTI_IMAGE_HINT.format(count=len(images))
    content: list[dict] = [{"type": "text", "text": prompt}]
    content += [{"type": "image_url", "image_url": {"url": url}} for url in images]
    messages = [
        {"role": "system", "content": TRANSCRIBE_SYSTEM},
        {"role": "user", "content": content},
    ]
    parts: list[str] = []
    try:
        # Без размышлений: пересказ картинки — не та задача, ради которой стоит
        # ждать ещё и обдумывание, а показывать его тут всё равно негде.
        async for kind, delta in stream_chat(messages, enable_thinking=False):
            if kind == "content":
                parts.append(delta)
    except LLMError:
        return "", (f"«{filename}»: не удалось расшифровать изображение — модель "
                    f"недоступна. В следующих вопросах от картинки останется "
                    f"только имя файла.")
    text = "".join(parts).strip()
    if not text:
        return "", f"«{filename}»: модель вернула пустую расшифровку изображения."
    return text, ""
